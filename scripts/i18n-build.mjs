// Builds src/lib/i18n/{uz,en}.ts from scripts/i18n/*.tsv (ru \t uz \t en) and checks
// that every UI string in the code has a translation with matching {placeholders}.
// Usage: node scripts/i18n-build.mjs          (build + check)
//        node scripts/i18n-build.mjs --check  (check only, non-zero exit on problems)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { collectKeys } from "./i18n-keys.mjs";

const dir = new URL("./i18n/", import.meta.url);
const rows = new Map();
const problems = [];
for (const f of readdirSync(dir).filter((f) => f.endsWith(".tsv")).sort()) {
  for (const [i, line] of readFileSync(new URL(f, dir), "utf8").split("\n").entries()) {
    if (!line.trim()) continue;
    const cols = line.split("\t");
    if (cols.length !== 3) {
      problems.push(`${f}:${i + 1}: expected 3 columns, got ${cols.length}`);
      continue;
    }
    if (rows.has(cols[0])) problems.push(`${f}:${i + 1}: duplicate key «${cols[0]}»`);
    rows.set(cols[0], { uz: cols[1], en: cols[2] });
  }
}

// Extra params a translation may use that the Russian text doesn't print.
const EXTRA_PARAMS = { "1/{n} финала": ["teams"] };
const ph = (s) => new Set([...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]));
const keys = collectKeys();
for (const k of keys) {
  const r = rows.get(k);
  if (!r) {
    problems.push(`missing translation: «${k}»`);
    continue;
  }
  const allowed = new Set([...ph(k), ...(EXTRA_PARAMS[k] ?? [])]);
  for (const lang of ["uz", "en"]) {
    for (const p of ph(r[lang])) if (!allowed.has(p)) problems.push(`${lang}: unknown {${p}} in «${k}»`);
    for (const p of ph(k)) if (!ph(r[lang]).has(p) && !(EXTRA_PARAMS[k] ?? []).length) problems.push(`${lang}: {${p}} dropped in «${k}»`);
    if (!r[lang].trim()) problems.push(`${lang}: empty translation for «${k}»`);
  }
}
const unused = [...rows.keys()].filter((k) => !keys.includes(k));

if (!process.argv.includes("--check")) {
  for (const lang of ["uz", "en"]) {
    const body = [...rows.entries()]
      .filter(([k]) => keys.includes(k))
      .sort(([a], [b]) => a.localeCompare(b, "ru"))
      .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v[lang])},`)
      .join("\n");
    writeFileSync(
      new URL(`../src/lib/i18n/${lang}.ts`, import.meta.url),
      `// Generated by scripts/i18n-build.mjs from scripts/i18n/*.tsv. Do not edit by hand.\nimport type { Dict } from "./core";\n\nconst dict: Dict = {\n${body}\n};\n\nexport default dict;\n`,
    );
  }
}

console.log(`${keys.length} keys, ${rows.size} translations, ${unused.length} unused`);
if (unused.length) console.log("unused:", unused.join(" | "));
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
